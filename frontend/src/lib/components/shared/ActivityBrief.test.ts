import { afterEach, expect, it } from "vitest";
import { cleanup, fireEvent, render, screen } from "@testing-library/svelte";
import ActivityBrief from "./ActivityBrief.svelte";
import type { ActivityBriefEntry } from "$lib/api/activityBriefs";

afterEach(cleanup);
const brief: ActivityBriefEntry = {
	notificationId: "1",
	version: "2026-11-10T12:00:00Z",
	days: 3,
	status: "ready",
	since: "2026-11-07T12:00:00Z",
	updatedAt: "2026-11-10T12:00:00Z",
	bullets: [
		{ text: "@author asks @reader about attribution.", recipient: "for_you", evidenceIds: ["1"] },
		{
			text: "@reviewer asks the author about rollout.",
			recipient: "other_activity",
			evidenceIds: ["2"],
		},
	],
};

it("renders recipient groups with directed requests first and visually emphasized", () => {
	render(ActivityBrief, { props: { brief, compact: true } });
	expect(screen.getByText("Activity highlights")).toBeInTheDocument();
	expect(screen.getByText("Last 3 days")).toBeInTheDocument();
	expect(screen.getByText("For you")).toHaveClass("font-semibold", "text-indigo-700");
	expect(screen.getByText("For you").parentElement).toHaveClass("bg-indigo-50/80");
	expect(screen.getAllByRole("listitem").map((item) => item.textContent)).toEqual(
		brief.bullets.map((b) => b.text)
	);
	expect(screen.queryByText(/Mock|Luna preview/)).not.toBeInTheDocument();
});

it("hides empty recipient groups when switching notifications", async () => {
	const { rerender } = render(ActivityBrief, { props: { brief } });
	await rerender({ brief: { ...brief, bullets: [brief.bullets[1]] } });
	expect(screen.queryByText("For you")).not.toBeInTheDocument();
	expect(screen.getByText("Other activity")).toBeInTheDocument();
	expect(screen.queryByText(/No direct requests/)).not.toBeInTheDocument();
});

it("keeps window and coverage limitations available without crowding the highlights", async () => {
	render(ActivityBrief, { props: { brief: { ...brief, warnings: ["History truncated."] } } });
	expect(screen.getByText(/Generated by Copilot/)).toBeInTheDocument();
	const disclosure = screen.getByText(/Window and coverage/);
	expect(disclosure.closest("details")).not.toHaveAttribute("open");
	await fireEvent.click(disclosure);
	expect(disclosure.closest("details")).toHaveAttribute("open");
	expect(screen.getByText(/Not an archive baseline/)).toBeVisible();
	expect(screen.getByText("History truncated.")).toBeVisible();
});

it("distinguishes no selected highlights from no activity or no action", () => {
	render(ActivityBrief, { props: { brief: { ...brief, bullets: [] } } });
	expect(screen.getByText("No highlights selected for this window.")).toBeInTheDocument();
	expect(screen.queryByText(/no action needed/i)).not.toBeInTheDocument();
});

it("keeps empty cached results to one quiet line in notification cards", () => {
	render(ActivityBrief, { props: { brief: { ...brief, bullets: [] }, compact: true } });
	expect(screen.getByText("No highlights selected")).toBeInTheDocument();
	expect(screen.getByText("Last 3 days")).toBeInTheDocument();
	expect(screen.queryByText("No highlights selected for this window.")).not.toBeInTheDocument();
});

it("shows queue and error states explicitly", async () => {
	const { rerender } = render(ActivityBrief, {
		props: { brief: { ...brief, status: "queued", bullets: [] } },
	});
	expect(screen.getByRole("status")).toHaveTextContent("Queued");
	await rerender({
		brief: { ...brief, status: "failed", error: "Provider unavailable", bullets: [] },
	});
	expect(screen.getByRole("alert")).toHaveTextContent("Provider unavailable");
});

it("renders no section without a result or for stopped work", async () => {
	const { container, rerender } = render(ActivityBrief);
	expect(container.querySelector("section")).toBeNull();
	await rerender({ brief: { ...brief, status: "cancelled" } });
	expect(container.querySelector("section")).toBeNull();
});

it("does not interpret generated text as HTML", () => {
	const { container } = render(ActivityBrief, {
		props: {
			brief: {
				...brief,
				bullets: [{ ...brief.bullets[0], text: "@someone <img src=x onerror=alert(1)>" }],
			},
		},
	});
	expect(container.querySelector("img")).toBeNull();
	expect(screen.getByText("@someone <img src=x onerror=alert(1)>")).toBeInTheDocument();
});
