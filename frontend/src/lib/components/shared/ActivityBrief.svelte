<script lang="ts">
	import type { ActivityBriefEntry } from "$lib/api/activityBriefs";
	export let brief: ActivityBriefEntry | undefined = undefined;
	export let compact = false;
	$: groups = [
		{ label: "For you", recipient: "for_you", directed: true },
		{ label: "Other activity", recipient: "other_activity", directed: false },
	]
		.map((group) => ({
			...group,
			bullets: brief?.bullets.filter((bullet) => bullet.recipient === group.recipient) ?? [],
		}))
		.filter((group) => group.bullets.length > 0);
</script>

{#if brief && brief.status !== "cancelled"}
	<section
		aria-label="Activity highlights"
		class={compact
			? "space-y-2 border-l-2 border-gray-200 pl-3 dark:border-gray-700"
			: "space-y-3 rounded-xl border border-gray-200 bg-gray-50/70 px-4 py-3 dark:border-gray-800 dark:bg-gray-900/40"}
	>
		<div
			class="flex flex-wrap items-center gap-x-2 gap-y-1 text-[11px] text-gray-500 dark:text-gray-400"
		>
			<span class="font-medium"
				>{compact && brief.status === "ready" && groups.length === 0
					? "No highlights selected"
					: "Activity highlights"}</span
			>
			<span aria-hidden="true">·</span>
			<span
				>Last {brief.days}
				{brief.days === 1 ? "day" : "days"}
			</span>
			{#if brief.status === "queued" || brief.status === "running"}
				<span role="status"> · {brief.status === "queued" ? "Queued" : "Summarizing…"}</span>
			{/if}
		</div>
		{#if brief.status === "failed"}
			<p role="alert" class="text-xs text-red-600 dark:text-red-400">{brief.error}</p>
		{:else if !compact && brief.status === "ready" && groups.length === 0}
			<p class="text-xs text-gray-500 dark:text-gray-400">
				No highlights selected for this window.
			</p>
		{/if}
		{#each groups as group (group.recipient)}
			<div
				class={group.directed ? "rounded-md bg-indigo-50/80 px-2.5 py-2 dark:bg-indigo-500/10" : ""}
			>
				<p
					class="text-[11px] {group.directed
						? 'font-semibold text-indigo-700 dark:text-indigo-300'
						: 'font-medium text-gray-500 dark:text-gray-400'}"
				>
					{group.label}
				</p>
				<ul
					class="list-disc space-y-1 pl-4 {group.directed
						? 'mt-1 font-medium text-gray-950 dark:text-white'
						: 'text-gray-700 dark:text-gray-300'} {compact
						? 'text-xs leading-relaxed'
						: 'text-sm leading-relaxed'}"
				>
					{#each group.bullets as bullet, index (index)}
						<li class="wrap-anywhere">{bullet.text}</li>
					{/each}
				</ul>
			</div>
		{/each}
		{#if !compact && brief.status === "ready"}
			<p class="mt-2 text-[11px] text-gray-500 dark:text-gray-400">
				Generated by Copilot · Recipient classification is inferred, not an all-clear.
			</p>
			<details class="text-[11px] text-gray-500 dark:text-gray-400">
				<summary class="cursor-pointer hover:text-gray-700 dark:hover:text-gray-300"
					>Window and coverage{brief.warnings?.length
						? ` · ${brief.warnings.length} notes`
						: ""}</summary
				>
				<p class="mt-2">
					Since {new Date(brief.since).toLocaleString()} · Not an archive baseline.
				</p>
				{#each brief.warnings ?? [] as warning, index (index)}
					<p class="mt-1 text-[11px] text-gray-500 dark:text-gray-400">{warning}</p>
				{/each}
			</details>
		{/if}
	</section>
{/if}
